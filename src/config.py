"""
训练与推理的公共配置。

为什么需要这个文件
------------------
训练（train.py）和推理（recognize.py）之间是**通过文件耦合**的：
train.py 产出 trainer/trainer.yml，recognize.py 再读它。

这种耦合有个隐蔽的危险：**如果两边对「人脸长什么样」的假设不一致，
程序不会报错，但结果会悄悄变差**。比如训练时把人脸裁成 100x100 存进模型、
推理时裁成 80x80 去比对——代码能跑，没有任何报错，但 LBPH 的网格特征
全都对不上，识别率直接崩掉，而且从报错信息里看不出任何线索。

所以凡是「两边必须一致」的量，全部集中放在这里，改一处两边同时生效。
"""

# ---------------- 人脸处理 ----------------

# 人脸裁片统一缩放到的尺寸。训练与推理必须完全一致。
FACE_SIZE = (100, 100)

# 人脸检测用的 Haar 级联分类器文件名。
# 完整路径由 cv2.data.haarcascades 动态拼接（随 OpenCV 安装，不写死本机路径）。
CASCADE_FILE = 'haarcascade_frontalface_alt2.xml'

# 人脸检测参数，训练与推理必须完全一致。
# 用法：detector.detectMultiScale(gray, **DETECT_PARAMS)
#
# 各项含义：
#   scaleFactor  —— 每次把检测窗口放大多少倍（越小越慢越细）
#   minNeighbors —— 一个候选框要被多少个邻近框「投票」才认定是人脸。
#                   调大 = 更严格（少误检，可能漏检）；调小 = 更宽松。
#   minSize      —— 小于这个尺寸的框直接忽略，避免把噪点当人脸。
#
# 为什么取 minNeighbors=5：
#   推理端面对的是真实摄像头与杂乱背景，用 5 更不容易把误检框当人脸，
#   也避免训练时把误检样本喂进模型。在 ORL 留出集上代价约 1 个百分点。
DETECT_PARAMS = {
    'scaleFactor': 1.1,
    'minNeighbors': 5,
    'minSize': (30, 30),
}

# 置信度阈值：LBPH 的置信度是「距离」，越小越像，超过该值判为陌生人。
#
# 这个值不是拍脑袋定的，而是在 ORL 数据上实测出来的。测法：
#   登记照用每人前 5 张，查询用同一人后 5 张（熟人）+ 另外 5 个没登记的人（陌生人）
# 实测距离分布：
#   熟人（同一人、不同照片）  50.0 ~ 90.5
#   陌生人（从没登记过）      71.9 ~ 98.0
# 两类【有重叠】，所以不存在完美阈值，只能权衡：
#   阈值 60 -> 陌生人放行 0%，但熟人只有 27% 能通过（误拒太多）
#   阈值 80 -> 熟人通过 90%，但陌生人有 37% 被放行（预警失效）
#   阈值 74 -> 陌生人放行约 5%，熟人通过约 79%  <- 取这个
#
# 取舍理由：对预警系统来说，「陌生人被放行」比「熟人被误拒」严重得多，
# 所以宁可偏严格。换 Fisherfaces / Eigenfaces 都试过，重叠更严重，LBPH 已是最好。
#
# 换自己的数据时必须重新标定：用带标注的视频跑
#   python recognize.py 视频 --truth <姓名>
# 观察输出的距离分布，再定阈值。
UNKNOWN_THRESHOLD = 74


# ---------------- 预警系统参数 ----------------

# 留出身份：这些人**不参与训练**，识别时会被判为「陌生人」。
#
# 这是预警系统的真实形态——模型只认识「已知人员」，名单外的人一律是陌生人。
# 同时也是机器学习里的 holdout 做法：留出一部分数据不训练，
# 用来检验模型对没见过的输入是什么反应。
#
# 本仓库用它来演示「陌生人累计告警」这条路径：
# samples/demo_stranger.avi 就是由这些留出身份拼成的。
HOLDOUT_SUBJECTS = {36, 37, 38, 39, 40}

# 累计多少帧「陌生人」后触发报警。
# 注意是**累计**而不是连续——画面里的人走开再回来，计数不会清零，
# 避免有人反复快速经过来躲避告警。
# 只有识别出「已知人员」时才把计数清零。
UNKNOWN_TRIGGER_FRAMES = 70

# 两次报警短信之间的最短间隔（秒），防止刷屏
SMS_COOLDOWN = 60


# ---------------- 文件路径（相对项目根目录）----------------

# 数据目录
DATA_DIR = 'data'

# 训练产出的模型
TRAINER_PATH = 'trainer/trainer.yml'

# 标签 id -> 姓名 的映射，由 train.py 生成
LABELS_PATH = 'trainer/labels.json'
